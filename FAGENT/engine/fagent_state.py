"""Serializable state schema for LangGraph execution."""

# ==============================================================================
# SECTION 1: Standard Typing Imports
# ==============================================================================
from typing import Any, TypedDict


# ==============================================================================
# SECTION 2: Graph State Schema Definition
# ==============================================================================
class FagentState(TypedDict, total=False):
    """Execution state passed between LangGraph nodes during DRC/LVS workflows.
    
    Fields:
        messages: Conversation history of chat/tool messages.
        rundir: Working directory path for artifacts and intermediate files.
        candidate_path: Filepath to the active layout GDS candidate.
        iteration: Current loop/retry iteration count.
        validation: Results from DRC/LVS validation runs.
        result: Final aggregated workflow outcome dictionary.
        review: Review evaluation metrics or verdicts.
        save_requested: Flag indicating user/model requested layout persistence.
        review_finished: Flag indicating review phase completion.
        inputs: Initial workflow task inputs.
        response: Output response payload generated by nodes.
        repair_error: Captured error message during DRC/layout repair.
        inspected: List of inspected element IDs or rule names.
        identity: Run metadata, timestamp, or model identity.
        candidate_digest: SHA256/hash of candidate layout to detect modifications.
    """
    messages: list[dict[str, Any]]
    rundir: str
    candidate_path: str
    iteration: int
    validation: dict[str, Any] | None
    result: dict[str, Any]
    review: dict[str, Any]
    save_requested: bool
    review_finished: bool
    inputs: dict[str, Any]
    response: dict[str, Any]
    repair_error: str
    inspected: list[str]
    identity: dict[str, Any]
    candidate_digest: str | None
    checklist: dict[str, Any] | None
    checklist_digest: str | None
    checklist_path: str | None
    task_state: dict[str, Any]
    drc_context: dict[str, Any]
    report: dict[str, Any]
    failed: bool
    pending_tools: bool
    plan: dict[str, Any] | None
    replan_context: dict[str, Any] | None
    replan_count: int
    proposals: dict[str, Any]
